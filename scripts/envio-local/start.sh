#!/bin/bash
# LEASH testnet indexer, self-hosted on this Mac: envio dev (Postgres + Hasura in Docker) + read-only proxy + Cloudflare
# quick tunnel → prints the public ENVIO_URL. Fallback while Envio Cloud can't deploy (see docs/LIMITATIONS.md).
#   scripts/envio-local/start.sh          # resume (keeps indexed data)
#   RESET=1 scripts/envio-local/start.sh  # re-index from the start block
#   scripts/envio-local/stop.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LOGS="$HOME/.leash-local"; mkdir -p "$LOGS"
cd "$ROOT/indexer"

# RPC from services/api/.env (never printed); config.local.yaml is gitignored and only holds ${ENVIO_LOCAL_RPC_URL}.
export ENVIO_LOCAL_RPC_URL="$(grep '^MONAD_TESTNET_RPC_URL=' "$ROOT/services/api/.env" | cut -d= -f2- | tr -d '"'"'"' \r')"
[ -n "$ENVIO_LOCAL_RPC_URL" ] || { echo "MONAD_TESTNET_RPC_URL missing in services/api/.env"; exit 1; }
python3 - <<'PY'
s = open("config.yaml").read()
s = s.replace("    rpc: https://testnet-rpc.monad.xyz\n", "    rpc:\n      - url: ${ENVIO_LOCAL_RPC_URL}\n        for: sync\n")
open("config.local.yaml", "w").write("# GENERATED by scripts/envio-local/start.sh (gitignored). RPC sync via QuickNode (1000-block getLogs).\n" + s)
PY

# Docker Desktop's credential helper hangs on this Mac; public images need no credentials.
export DOCKER_CONFIG="$LOGS/dockercfg"; mkdir -p "$DOCKER_CONFIG"; [ -f "$DOCKER_CONFIG/config.json" ] || echo '{}' > "$DOCKER_CONFIG/config.json"
for d in contexts cli-plugins buildx; do [ -e "$HOME/.docker/$d" ] && ln -sfn "$HOME/.docker/$d" "$DOCKER_CONFIG/$d"; done
export DOCKER_CONTEXT=desktop-linux TUI_OFF=true LOG_STRATEGY=console-raw LOG_LEVEL=info

pkill -f "envio dev --config config.local.yaml" 2>/dev/null || true
FLAGS=""; [ "${RESET:-0}" = "1" ] && FLAGS="-r"
nohup pnpm envio dev --config config.local.yaml $FLAGS > "$LOGS/envio.log" 2>&1 &
echo "indexer starting (log: $LOGS/envio.log)"
until curl -s -o /dev/null -w '%{http_code}' localhost:8080/healthz 2>/dev/null | grep -q 200; do sleep 2; done
echo "hasura up on localhost:8080 (local only)"

pkill -f "scripts/envio-local/proxy.mjs" 2>/dev/null || true
nohup node "$ROOT/scripts/envio-local/proxy.mjs" > "$LOGS/proxy.log" 2>&1 &
until curl -s localhost:8090/healthz >/dev/null 2>&1; do sleep 1; done
echo "read-only proxy up on localhost:8090"

pkill -f "cloudflared tunnel --url http://localhost:8090" 2>/dev/null || true
: > "$LOGS/tunnel.log"
nohup cloudflared tunnel --no-autoupdate --url http://localhost:8090 > "$LOGS/tunnel.log" 2>&1 &
for _ in $(seq 1 60); do URL=$(grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' "$LOGS/tunnel.log" | head -1 || true); [ -n "$URL" ] && break; sleep 1; done
[ -n "${URL:-}" ] || { echo "tunnel did not start (see $LOGS/tunnel.log)"; exit 1; }
echo "$URL/v1/graphql" > "$LOGS/ENVIO_URL"
echo "ENVIO_URL=$URL/v1/graphql"
